"""
Analytics Subsystem - Comprehensive Report Generator.
Generates structured Markdown and standalone interactive HTML reports.
"""

from typing import Dict, List, Any
import os
from datetime import datetime


class ReportGenerator:
    """
    Transforms raw session analytics and attendance data into
    mentor-ready and educator-friendly summary reports.
    """

    def __init__(self, output_dir: str = "session_records"):
        self.output_dir = output_dir
        os.makedirs(self.output_dir, exist_ok=True)

    def generate_markdown_report(
        self,
        session_info: Dict[str, Any],
        attendance_records: List[Dict],
        analytics_data: Dict[str, Any],
        suggestions_log: List[Dict]
    ) -> str:
        """
        Creates a clean Markdown evaluation report.
        """
        now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        present_count = sum(1 for r in attendance_records if r.get("status") == "PRESENT")
        transient_count = sum(1 for r in attendance_records if r.get("status") == "TRANSIENT_IGNORED")
        total_tracked = len(attendance_records)

        md = f"""# 📊 Multimodal Attendance & Engagement Session Report
**Generated On:** {now_str}  
**Session ID:** {session_info.get('session_id', 'Session_Auto')}  
**Mode:** Privacy-Preserving Offline Edge Deployment  

---

## 1. Executive Summary
- **Total Tracked Candidates:** {total_tracked}
- **Confirmed Attendance (Sustained Presence Verified):** {present_count}
- **Transient Detections Filtered Out:** {transient_count}
- **Session Attendance Rate:** {(present_count / max(1, total_tracked) * 100.0):.1f}%
- **Average Classroom Engagement:** {analytics_data.get('average_engagement', 0.0)}%
- **Peak Engagement:** {analytics_data.get('peak_engagement', 0.0)}%
- **Attention Drop Incidents:** {analytics_data.get('drop_events_count', 0)}
- **Interaction Peaks:** {analytics_data.get('peak_events_count', 0)}

---

## 2. Attendance & Sustained Presence Verification (Scenario 1)
Attendance is marked strictly on **sustained presence** (threshold >= 60% session time or configurable minimum seconds), effectively preventing false positives from transient appearances.

| Participant ID | Status | First Seen | Last Seen | Present (Mins) | Presence % | Verified Status |
|---|---|---|---|---|---|---|
"""
        for r in attendance_records:
            status_badge = "✅ PRESENT" if r.get("status") == "PRESENT" else ("⚠️ TRANSIENT_IGNORED" if r.get("status") == "TRANSIENT_IGNORED" else "❌ ABSENT")
            md += f"| {r.get('participant_id')} | {status_badge} | {r.get('first_seen')} | {r.get('last_seen')} | {r.get('total_present_minutes')} | {r.get('presence_percentage')}% | {r.get('attendance_timestamp')} |\n"

        md += """
---

## 3. Multimodal Engagement & Dynamics (Scenario 2)
The system fuses **head pose gaze vectors, motion patterns, inactivity intervals**, and **classroom acoustics** to generate real-time engagement telemetry.

### Interval Telemetry Breakdown:
| Minute Interval | Average Engagement | Visual Focus Index | Audio Activity Index |
|---|---|---|---|
"""
        intervals = analytics_data.get("intervals", [])
        if intervals:
            for inv in intervals:
                md += f"| Minute {inv.get('interval_minute')} | {inv.get('avg_engagement')}% | {inv.get('avg_visual')}% | {inv.get('avg_audio')}% |\n"
        else:
            md += "| Overall Session | " + str(analytics_data.get('average_engagement', 0.0)) + "% | Normal | Normal |\n"

        md += """
---

## 4. AI-Driven Pedagogical Suggestions (Scenario 3)
Real-time, assistive teaching suggestions generated by the decision-support engine:

"""
        if suggestions_log:
            for s in suggestions_log:
                md += f"- **[{s.get('time')}] [{s.get('category')}] ({s.get('urgency')} Urgency)**: {s.get('suggestion')}\n  *Rationale:* {s.get('rationale')}\n\n"
        else:
            md += "*No critical intervention alerts were triggered during this balanced session.*\n"

        md += """
---
*Report generated automatically by Multimodal Attendance & Engagement Agent.*
"""
        filepath = os.path.join(self.output_dir, f"{session_info.get('session_id', 'Session')}_summary.md")
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(md)

        return filepath

    def generate_html_report(
        self,
        session_info: Dict[str, Any],
        attendance_records: List[Dict],
        analytics_data: Dict[str, Any],
        suggestions_log: List[Dict]
    ) -> str:
        """
        Creates an interactive, beautiful HTML report that can be opened in any web browser.
        """
        now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        present_count = sum(1 for r in attendance_records if r.get("status") == "PRESENT")
        transient_count = sum(1 for r in attendance_records if r.get("status") == "TRANSIENT_IGNORED")
        total_tracked = len(attendance_records)
        avg_eng = analytics_data.get('average_engagement', 0.0)

        rows_html = ""
        for r in attendance_records:
            is_p = r.get("status") == "PRESENT"
            is_t = r.get("status") == "TRANSIENT_IGNORED"
            badge_class = "badge-success" if is_p else ("badge-warning" if is_t else "badge-danger")
            badge_text = "PRESENT (Verified)" if is_p else ("TRANSIENT (Ignored)" if is_t else "INSUFFICIENT PRESENCE")
            rows_html += f"""
            <tr>
                <td><code>{r.get('participant_id')}</code></td>
                <td><span class="badge {badge_class}">{badge_text}</span></td>
                <td>{r.get('first_seen')}</td>
                <td>{r.get('last_seen')}</td>
                <td>{r.get('total_present_minutes')} min</td>
                <td><strong>{r.get('presence_percentage')}%</strong></td>
                <td>{r.get('attendance_timestamp')}</td>
            </tr>
            """

        suggestions_html = ""
        for s in suggestions_log:
            urg = s.get("urgency", "LOW")
            border_col = "#22c55e" if urg == "LOW" else ("#f59e0b" if urg == "MEDIUM" else "#ef4444")
            suggestions_html += f"""
            <div class="card suggestion-card" style="border-left: 5px solid {border_col}; margin-bottom: 12px; padding: 12px 16px;">
                <div style="display:flex; justify-content:space-between; margin-bottom:6px;">
                    <span style="font-weight:700; color:{border_col};">{s.get('category')} ({urg})</span>
                    <span style="color:#64748b; font-size:12px;">{s.get('time')}</span>
                </div>
                <div style="font-size:14px; color:#1e293b; margin-bottom:4px;">{s.get('suggestion')}</div>
                <div style="font-size:12px; color:#64748b; font-style:italic;">Reason: {s.get('rationale')}</div>
            </div>
            """

        html = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Classroom Intelligence Report - {session_info.get('session_id', 'Session')}</title>
    <style>
        body {{ font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; background: #f8fafc; color: #1e293b; margin: 0; padding: 24px; }}
        .container {{ max-width: 1100px; margin: 0 auto; background: #ffffff; border-radius: 12px; box-shadow: 0 4px 20px rgba(0,0,0,0.06); padding: 32px; }}
        .header {{ display: flex; justify-content: space-between; align-items: center; border-bottom: 2px solid #e2e8f0; padding-bottom: 20px; margin-bottom: 24px; }}
        .header h1 {{ margin: 0; font-size: 24px; color: #0f172a; }}
        .kpi-grid {{ display: grid; grid-template-columns: repeat(4, 1fr); gap: 16px; margin-bottom: 28px; }}
        .kpi-card {{ background: #f1f5f9; padding: 18px; border-radius: 8px; text-align: center; }}
        .kpi-val {{ font-size: 28px; font-weight: 700; color: #2563eb; margin: 4px 0; }}
        .kpi-lbl {{ font-size: 13px; color: #64748b; font-weight: 500; }}
        table {{ width: 100%; border-collapse: collapse; margin-top: 12px; }}
        th, td {{ padding: 12px 14px; text-align: left; border-bottom: 1px solid #e2e8f0; font-size: 14px; }}
        th {{ background: #f8fafc; color: #475569; font-weight: 600; }}
        .badge {{ display: inline-block; padding: 4px 8px; border-radius: 4px; font-size: 11px; font-weight: 700; }}
        .badge-success {{ background: #dcfce7; color: #166534; }}
        .badge-warning {{ background: #fef3c7; color: #92400e; }}
        .badge-danger {{ background: #fee2e2; color: #991b1b; }}
        .footer {{ margin-top: 32px; text-align: center; font-size: 12px; color: #94a3b8; border-top: 1px solid #e2e8f0; padding-top: 16px; }}
    </style>
</head>
<body>
<div class="container">
    <div class="header">
        <div>
            <h1>🎓 Multimodal Attendance & Engagement Report</h1>
            <div style="color: #64748b; font-size: 14px; margin-top: 4px;">Session: {session_info.get('session_id', 'Session_Auto')} | {now_str}</div>
        </div>
        <div style="background: #e0f2fe; color: #0369a1; padding: 6px 12px; border-radius: 6px; font-size: 13px; font-weight: 600;">
            Offline Edge Intelligence
        </div>
    </div>

    <div class="kpi-grid">
        <div class="kpi-card">
            <div class="kpi-val">{present_count}</div>
            <div class="kpi-lbl">Verified Present (Sustained)</div>
        </div>
        <div class="kpi-card">
            <div class="kpi-val" style="color:#d97706;">{transient_count}</div>
            <div class="kpi-lbl">Transient Filtered</div>
        </div>
        <div class="kpi-card">
            <div class="kpi-val" style="color:#059669;">{avg_eng}%</div>
            <div class="kpi-lbl">Avg Engagement Score</div>
        </div>
        <div class="kpi-card">
            <div class="kpi-val" style="color:#7c3aed;">{analytics_data.get('peak_engagement', 0.0)}%</div>
            <div class="kpi-lbl">Peak Interaction</div>
        </div>
    </div>

    <h2>📋 Attendance Verification Matrix (Scenario 1)</h2>
    <p style="font-size:13px; color:#64748b;">Attendance is confirmed only when sustained presence criteria (continuous duration &gt; 60%) are satisfied. Transient appearances are automatically excluded.</p>
    <table>
        <thead>
            <tr>
                <th>Participant</th>
                <th>Status</th>
                <th>First Seen</th>
                <th>Last Seen</th>
                <th>Present Duration</th>
                <th>Presence %</th>
                <th>Timestamp Marked</th>
            </tr>
        </thead>
        <tbody>
            {rows_html}
        </tbody>
    </table>

    <h2 style="margin-top:32px;">🤖 AI Pedagogical Insights & Suggestions (Scenario 3)</h2>
    <div>
        {suggestions_html or '<p style="color:#64748b;">No high-priority intervention triggers occurred.</p>'}
    </div>

    <div class="footer">
        Multimodal Attendance & Engagement Agent &bull; Designed for Ethical, Privacy-Preserving Classroom AI
    </div>
</div>
</body>
</html>"""
        filepath = os.path.join(self.output_dir, f"{session_info.get('session_id', 'Session')}_report.html")
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(html)

        return filepath
